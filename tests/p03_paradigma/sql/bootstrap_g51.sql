BEGIN;

DO $$
BEGIN
  IF current_database() <> 'licitagym_g51' THEN
    RAISE EXCEPTION 'Bootstrap bloqueado: banco inesperado (%)',
      current_database();
  END IF;

  IF to_regclass('public.licitacao_documentos') IS NOT NULL
     OR to_regclass('public.licitacao_documento_versoes') IS NOT NULL THEN
    RAISE EXCEPTION 'Bootstrap bloqueado: tabelas já existentes';
  END IF;
END
$$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role NOLOGIN;
  END IF;
END
$$;

CREATE TABLE public.licitacao_documentos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

