-- G5.2: migration de aplicação para versionamento documental imutável.
-- Validada no Supabase Preview; produção requer gate próprio.
CREATE TABLE IF NOT EXISTS public.licitacao_documento_versoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  documento_id bigint NOT NULL REFERENCES public.licitacao_documentos(id) ON DELETE RESTRICT,
  sha256 text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  storage_uri text NOT NULL CHECK (length(btrim(storage_uri)) > 0),
  tamanho_bytes bigint NOT NULL CHECK (tamanho_bytes >= 0),
  mime_type text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT licitacao_documento_versoes_documento_sha_key UNIQUE (documento_id, sha256)
);
-- RLS limita clientes comuns; não substitui privilégios e triggers.
ALTER TABLE public.licitacao_documento_versoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.licitacao_documento_versoes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.licitacao_documento_versoes_id_seq FROM PUBLIC, anon, authenticated;
-- O backend atual utiliza service_role. Conferir grants do ambiente antes de ativar.
GRANT SELECT, INSERT ON TABLE public.licitacao_documento_versoes TO service_role;
GRANT USAGE ON SEQUENCE public.licitacao_documento_versoes_id_seq TO service_role;
CREATE OR REPLACE FUNCTION public.bloquear_mutacao_licitacao_documento_versoes()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  RAISE EXCEPTION 'Histórico documental imutável: UPDATE/DELETE proibido';
END;
$$;
REVOKE ALL ON FUNCTION public.bloquear_mutacao_licitacao_documento_versoes()
FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS trg_bloquear_mutacao_licitacao_documento_versoes ON public.licitacao_documento_versoes;
CREATE TRIGGER trg_bloquear_mutacao_licitacao_documento_versoes
BEFORE UPDATE OR DELETE ON public.licitacao_documento_versoes
FOR EACH ROW EXECUTE FUNCTION public.bloquear_mutacao_licitacao_documento_versoes();
